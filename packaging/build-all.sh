#!/usr/bin/env bash
# cava-bg — Build ALL packaging artifacts.
#
# Usage:  ./packaging/build-all.sh [--allow-dirty]
#
# Produces, in target/dist/:
#   cava-bg-<v>.tar.gz                        source tarball  (+ .sha256)
#   cava-bg-<v>-<arch>.tar.gz                 binary tarball  (+ .sha256)
#   cava-bg_<v>-1_amd64.deb                   Debian/Ubuntu
#   cava-bg-<v>-1.<arch>.rpm                  Fedora/openSUSE
#   cava-bg-aur-<v>.tar.gz                    PKGBUILD + .SRCINFO for AUR
#
# In CI (release.yml) the same script runs and the artifacts are uploaded to a
# GitHub release automatically.
set -euo pipefail

export PATH="$HOME/.cargo/bin:$PATH"

PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=../scripts/version.sh
source "$PROJECT_DIR/scripts/version.sh"
export CAVA_BG_ROOT="$PROJECT_DIR"

ALLOW_DIRTY=0
for arg in "$@"; do
    case "$arg" in
        --allow-dirty) ALLOW_DIRTY=1 ;;
        -h|--help)
            sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        *) echo "unknown argument: $arg" >&2; exit 2 ;;
    esac
done

VERSION="$(cava_bg_version)"
PKG_NAME="$CAVA_BG_NAME"
TAG="${VERSION}"
DIST_DIR="$PROJECT_DIR/target/dist"
ARCH="${CAVA_BG_ARCH:-$(rustc -vV | sed -n 's/^host: //p')}"

cd "$PROJECT_DIR"

if [ "$ALLOW_DIRTY" -eq 0 ] && cava_bg_is_dirty; then
    echo "error: refusing to package a dirty tree (pass --allow-dirty to override)." >&2
    git status --short >&2
    exit 1
fi

echo "╔════════════════════════════════════════════════╗"
echo "║  cava-bg ${TAG} — Package All the Things       ║"
echo "╚════════════════════════════════════════════════╝"
echo ""

rm -rf "$DIST_DIR"
mkdir -p "$DIST_DIR"

# ─── 1. Release binary ───
echo "┌─ [1/6] Building release binary..."
cava_bg_build_release
echo "├─ Done: target/release/${PKG_NAME}"
echo ""

# ─── 2. Source tarball ───
echo "┌─ [2/6] Creating source tarball..."
SRC_TAR="$DIST_DIR/${PKG_NAME}-${VERSION}.tar.gz"
git archive --prefix="${PKG_NAME}-${VERSION}/" -o "$SRC_TAR" HEAD
cava_bg_sha256 "$SRC_TAR"
echo "├─ Done: $(basename "$SRC_TAR")"
echo ""

# ─── 3. Binary tarball ───
echo "┌─ [3/6] Creating binary tarball..."
BIN_DIR="$DIST_DIR/${PKG_NAME}-${VERSION}-${ARCH}"
mkdir -p "$BIN_DIR"
cp "target/release/${PKG_NAME}" "$BIN_DIR/"
# Generated by the binary, so the shipped defaults can never drift from
# `Config::default()` the way the old hand-maintained config.toml did.
"target/release/${PKG_NAME}" __default-config >"$BIN_DIR/config.toml"
cp README.md LICENSE "$BIN_DIR/"
[ -d target/release/completions ] && cp -r target/release/completions "$BIN_DIR/"
tar czf "$DIST_DIR/${PKG_NAME}-${VERSION}-${ARCH}.tar.gz" -C "$DIST_DIR" "$(basename "$BIN_DIR")"
cava_bg_sha256 "$DIST_DIR/${PKG_NAME}-${VERSION}-${ARCH}.tar.gz"
rm -rf "$BIN_DIR"
echo "├─ Done: ${PKG_NAME}-${VERSION}-${ARCH}.tar.gz"
echo ""

# ─── 4. DEB ───
# Always via packaging/deb/build-deb.sh. `cargo deb` was removed as an option
# because it builds its dependency list from [package.metadata.deb] in
# Cargo.toml, which is a second source of truth that silently drifts from
# packaging/deb/control — that is how a `Depends: wayland` line (a package that
# does not exist on Debian) reached a published .deb.
echo "┌─ [4/6] Creating .deb package..."
if command -v dpkg-deb >/dev/null; then
    VERSION="$VERSION" bash "$PROJECT_DIR/packaging/deb/build-deb.sh"
    cp "$DIST_DIR"/*.deb "$DIST_DIR/" 2>/dev/null || true
    echo "├─ Done: $(ls "$DIST_DIR"/*.deb 2>/dev/null)"
else
    echo "├─ SKIPPED: dpkg-deb unavailable (run on Debian/Ubuntu, or in a container)"
fi
echo ""

# ─── 5. RPM ───
# Same reasoning as the .deb: rpmbuild consumes packaging/rpm/cava-bg.spec,
# which has to stay the one place the RPM dependency list lives.
echo "┌─ [5/6] Creating .rpm package..."
if [ -n "${CAVA_BG_SKIP_RPM:-}" ]; then
    # An RPM has to be built on an RPM distro. rpmbuild checks BuildRequires
    # against package names that only exist on Fedora/openSUSE (cargo,
    # dbus-devel, ffmpeg-devel, mesa-libEGL-devel...), so it cannot run on the
    # Debian/Ubuntu runner at all. Reaching for --nodeps would be worse: the
    # resulting binary would link against the wrong sonames and still be
    # installed on Fedora. The release workflow builds it in a Fedora container
    # instead, and sets this to skip it here.
    echo "├─ SKIPPED: CAVA_BG_SKIP_RPM is set (see the rpm job in release.yml)"
elif command -v rpmbuild >/dev/null; then
    VERSION="$VERSION" bash "$PROJECT_DIR/packaging/rpm/build-rpm.sh"
    cp "$PROJECT_DIR/target/rpm"/*.rpm "$DIST_DIR/" 2>/dev/null || true
    echo "├─ Done: $(ls "$DIST_DIR"/*.rpm 2>/dev/null)"
else
    echo "├─ SKIPPED: rpmbuild unavailable (run on Fedora/openSUSE, or in a container)"
fi
echo ""

# ─── 6. AUR submission tarball ───
echo "┌─ [6/6] Rendering AUR PKGBUILD..."
VERSION="$VERSION" ARCH="$ARCH" bash "$PROJECT_DIR/packaging/aur/render-pkgbuild.sh"
AUR_DIR="$DIST_DIR/aur-${PKG_NAME}"
rm -rf "$AUR_DIR"
mkdir -p "$AUR_DIR"
cp "$DIST_DIR/aur-files/PKGBUILD" "$AUR_DIR/"
cp "$DIST_DIR/aur-files/.SRCINFO" "$AUR_DIR/"
tar czf "$DIST_DIR/${PKG_NAME}-aur-${VERSION}.tar.gz" -C "$DIST_DIR" "aur-${PKG_NAME}"
echo "├─ Done: ${PKG_NAME}-aur-${VERSION}.tar.gz"
echo ""

echo "╔════════════════════════════════════════════════╗"
echo "║  Artifacts in target/dist/                     ║"
echo "╚════════════════════════════════════════════════╝"
ls -lh "$DIST_DIR/"
echo ""
echo "Release tag (cut by CI on merge to main):  ${TAG}"
echo "AUR: https://aur.archlinux.org/packages/${PKG_NAME}"
